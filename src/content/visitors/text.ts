/* ============================================================
   STALL VISITORS — text

   There is almost none, and that is the design.

   A strange figure at the stall used to get a line of narration
   ("摊子边多了个影子…") and a badge on the home screen. Both are gone.
   The reason: a caption turns a thing you *noticed* into a thing you
   were *told*, and the noticing is the whole reward. A hood, a lantern
   at noon, a rim of colour nobody local has — that is the notice. If a
   player misses it, they miss it, and the figure will come again.

   What survives here is one tip, shown once, in the settings sheet
   where the rest of the how-to-play lives. It explains the *category*
   of thing without ever announcing an instance of it.
   ============================================================ */

